"""Reports router — FDR Register (CSV/PDF), Maturity Forecast (PDF), Discrepancy Summary (CSV)."""
import csv
import io
from datetime import timedelta
from fastapi import APIRouter, Depends, HTTPException
from fastapi.responses import StreamingResponse
from sqlalchemy.orm import Session
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib import colors
from reportlab.lib.units import cm
from reportlab.platypus import SimpleDocTemplate, Table, TableStyle, Paragraph, Spacer
from reportlab.lib.styles import getSampleStyleSheet
from src.config.database import get_db
from src.config.models import FDR, Deposit, Institution, DiscrepancyCase
from src.auth.auth import get_current_user, has_role
from src.auth.auth import SUPER_ADMIN, AICTE_OFFICER, AUDITOR
from src.config.dates import today as get_today
from src.audit.audit import write_audit

router = APIRouter()


def get_fdr_queryset(institution_id: str, current_user, db: Session):
    q = db.query(FDR).join(Deposit)
    if not has_role(current_user, SUPER_ADMIN, AICTE_OFFICER, AUDITOR):
        q = q.filter(Deposit.institution_id == current_user.institution_id)
    elif institution_id:
        q = q.filter(Deposit.institution_id == institution_id)
    return q


@router.get("/fdr-register")
def fdr_register(
    institution: str = None,
    format: str = "csv",
    db: Session = Depends(get_db),
    current_user=Depends(get_current_user),
):
    fdrs = get_fdr_queryset(institution, current_user, db).order_by(FDR.maturity_date).all()

    write_audit(db, user_id=current_user.id, entity_type="report", entity_id=None,
                action="GENERATE_FDR_REGISTER", after={"format": format, "count": len(fdrs)})
    db.commit()

    if format == "csv":
        output = io.StringIO()
        writer = csv.writer(output)
        writer.writerow([
            "FDR ID", "Deposit Ref", "Institution", "Bank", "FDR Number",
            "Principal (₹)", "Rate (%)", "Start Date", "Maturity Date", "Status", "Kind"
        ])
        for f in fdrs:
            writer.writerow([
                f.id, f.deposit.deposit_ref if f.deposit else "",
                f.deposit.institution.name if f.deposit and f.deposit.institution else "",
                f.bank.name if f.bank else "", f.fdr_number,
                f"{f.principal:,.2f}", f.rate or "", str(f.start_date), str(f.maturity_date),
                f.status, f.kind,
            ])
        output.seek(0)
        return StreamingResponse(
            iter([output.getvalue()]),
            media_type="text/csv",
            headers={"Content-Disposition": f"attachment; filename=fdr_register_{get_today()}.csv"}
        )

    elif format == "pdf":
        buf = io.BytesIO()
        doc = SimpleDocTemplate(buf, pagesize=landscape(A4), leftMargin=1*cm, rightMargin=1*cm)
        styles = getSampleStyleSheet()
        story = [
            Paragraph(f"FDR Register — Generated {get_today()}", styles["Heading1"]),
            Paragraph(f"Generated by: {current_user.name} ({current_user.email})", styles["Normal"]),
            Spacer(1, 0.5*cm),
        ]
        data = [["FDR Number", "Institution", "Bank", "Principal (₹)", "Maturity Date", "Status"]]
        for f in fdrs:
            data.append([
                f.fdr_number,
                (f.deposit.institution.name[:30] if f.deposit and f.deposit.institution else ""),
                (f.bank.name[:20] if f.bank else ""),
                f"{f.principal/100000:.1f}L",
                str(f.maturity_date), f.status,
            ])
        t = Table(data, repeatRows=1)
        t.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1e40af")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTSIZE", (0, 0), (-1, -1), 8),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f1f5f9")]),
        ]))
        story.append(t)
        doc.build(story)
        buf.seek(0)
        return StreamingResponse(
            buf,
            media_type="application/pdf",
            headers={"Content-Disposition": f"attachment; filename=fdr_register_{get_today()}.pdf"}
        )
    else:
        raise HTTPException(status_code=422, detail="Format must be 'csv' or 'pdf'")


@router.get("/maturity-forecast")
def maturity_forecast(
    format: str = "pdf",
    institution: str = None,
    db: Session = Depends(get_db),
    current_user=Depends(get_current_user),
):
    today = get_today()
    end = today + timedelta(days=180)
    fdrs = (
        get_fdr_queryset(institution, current_user, db)
        .filter(FDR.maturity_date >= today, FDR.maturity_date <= end)
        .order_by(FDR.maturity_date)
        .all()
    )
    write_audit(db, user_id=current_user.id, entity_type="report", entity_id=None,
                action="GENERATE_MATURITY_FORECAST", after={"format": format, "count": len(fdrs)})
    db.commit()

    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4)
    styles = getSampleStyleSheet()
    story = [
        Paragraph(f"Maturity Forecast — Next 6 Months from {today}", styles["Heading1"]),
        Paragraph(f"Generated by: {current_user.name}", styles["Normal"]),
        Spacer(1, 0.5*cm),
    ]
    data = [["FDR Number", "Institution", "Principal (₹ L)", "Maturity Date", "Days Left", "Status"]]
    for f in fdrs:
        data.append([
            f.fdr_number,
            (f.deposit.institution.name[:25] if f.deposit and f.deposit.institution else ""),
            f"{f.principal/100000:.1f}",
            str(f.maturity_date),
            str((f.maturity_date - today).days),
            f.status,
        ])
    t = Table(data, repeatRows=1)
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0f766e")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f0fdf4")]),
    ]))
    story.append(t)
    doc.build(story)
    buf.seek(0)
    return StreamingResponse(
        buf, media_type="application/pdf",
        headers={"Content-Disposition": f"attachment; filename=maturity_forecast_{today}.pdf"}
    )


@router.get("/discrepancies")
def discrepancy_report(
    format: str = "csv",
    institution: str = None,
    db: Session = Depends(get_db),
    current_user=Depends(get_current_user),
):
    q = db.query(DiscrepancyCase)
    if not has_role(current_user, SUPER_ADMIN, AICTE_OFFICER, AUDITOR):
        q = (q.join(FDR, DiscrepancyCase.fdr_id == FDR.id)
               .join(Deposit, FDR.deposit_id == Deposit.id)
               .filter(Deposit.institution_id == current_user.institution_id))
    cases = q.order_by(DiscrepancyCase.opened_at.desc()).all()
    write_audit(db, user_id=current_user.id, entity_type="report", entity_id=None,
                action="GENERATE_DISCREPANCY_REPORT")
    db.commit()

    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow(["Case ID", "FDR ID", "Rule Code", "Severity", "Status", "Message", "Opened At"])
    for c in cases:
        writer.writerow([
            c.id, c.fdr_id,
            c.rule.code if c.rule else "",
            c.severity, c.status, c.message, str(c.opened_at)
        ])
    output.seek(0)
    return StreamingResponse(
        iter([output.getvalue()]),
        media_type="text/csv",
        headers={"Content-Disposition": f"attachment; filename=discrepancies_{get_today()}.csv"}
    )
